/// Expands its input only when the `sqlite` feature is enabled. Code
/// generated by Dinoco's derives wraps every SQLite-specific item in it, so it
/// compiles against whichever databases are enabled.
#[cfg(feature = "sqlite")]
#[doc(hidden)]
#[macro_export]
macro_rules! __dinoco_sqlite {
    ($($item:tt)*) => { $($item)* };
}

#[cfg(not(feature = "sqlite"))]
#[doc(hidden)]
#[macro_export]
macro_rules! __dinoco_sqlite {
    ($($item:tt)*) => {};
}

